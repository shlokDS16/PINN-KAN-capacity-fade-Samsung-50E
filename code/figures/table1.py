"""Table 1 (booktabs LaTeX + CSV for Word): arms x grid cells, Test C, S2 (PREREG_v4 section 14).

Panel A: forecast RMSE in pp, mean over held-out Test B conditions +- seed SD, for the nine grid cells (m = 8, 16, 32 training conditions x k = 0, 2, full check-ups);
best value per column in bold, second best underlined (sorting of the supplied values).
Panel B: Test C and S2 (k_full cell) mean +- seed SD; E/R_LOO and E/R_WARP = the supplied g4 mean divided by the supplied replicate-spread references ("replicate spread",
descriptive, never a margin); fit time, parameters and n_train_used at g4.
Inputs: --analysis (directory with arm_table.json and reference.json).
READ-ONLY. `arm_table.json` (per-arm pooled mean, seed SD, parameters, n_train_used, fit seconds per grid cell, Test C, S2) is NOT written by the statistics step yet
(ALIGN_V4_REPORT gap G1); `reference.json` (R_LOO, R_WARP) is not written on the Design R2 path either (gap G2). Without reference.json the E/R columns print "--".
No interval, tier or test appears in this table: they live in Fig. 4 and Table 2.
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pk_style as ps
import pk_data as pdt

ORDER = ["A1", "A2", "A4", "A5", "A9", "A10", "A10P", "A11", "A12", "A13", "A15", "G15", "R1", "R2"]
NAME = {"A1": "A1 PINN-KAN", "A2": "A2 Hard-ODE KAN", "A4": "A4 Additive GAM", "A5": "A5 Interaction GAM", "A9": "A9 Data-only $F$", "A10": "A10 Semi-empirical (per-cell factor)",
        "A10P": "A10 as published", "A11": "A11 GP-ARD", "A12": "A12 LightGBM", "A13": "A13 Cycling only", "A15": "A15 Extracted law", "G15": "G15 Extracted additive law",
        "R1": "R1 Persistence", "R2": "R2 Window-linear"}
MS, KS = (8, 16, 32), ("0", "2", "full")


def rank_marks(vals):
    """vals: arm -> float; lower is better. Sorting of supplied values."""
    v = sorted((x, a) for a, x in vals.items() if x is not None)
    out = {}
    if v:
        out[v[0][1]] = "best"
    if len(v) > 1:
        out[v[1][1]] = "second"
    return out


def fmt_cell(e, mk):
    s = f"{e['mean_pp']:.2f} $\\pm$ {e['seed_sd_pp']:.2f}"
    return f"\\textbf{{{s}}}" if mk == "best" else (f"\\underline{{{s}}}" if mk == "second" else s)


def main():
    ap = ps.common_args(__doc__)
    ap.add_argument("--analysis", required=True)
    a = ap.parse_args()
    an = Path(a.analysis)
    prov = ps.Provenance(an)
    prov.require_frozen("Table 1")
    T = ps.load_json(ps.need(an / "arm_table.json", "(statistics output arm_table.json: gap G1)"))
    ref = pdt.load_analysis_json(an, "reference.json", required=False)
    ref = (ref or {}).get("values", {}).get("B")
    cells = T["cells"]
    arms = [x for x in ORDER if any(x in cells[c] for c in cells)]
    cols = [f"{m}|{k}" for m in MS for k in KS if f"{m}|{k}" in cells]
    marks = {c: rank_marks({x: cells[c][x]["mean_pp"] for x in cells[c]}) for c in cols}
    g4 = cells.get("32|full", {})
    n_of = lambda c: next(iter(cells[c].values()))["n_conditions"]
    L = ["% Table 1, generated by code/figures/table1.py from the statistics-step files; do not edit by hand."]
    if prov.synthetic:
        L.append("% SYNTHETIC DEMO - NOT RESULTS")
    L += ["\\begin{table}[t]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.6pt}"]
    if prov.synthetic:
        L.append("{\\color{red}\\bfseries SYNTHETIC DEMO -- NOT RESULTS}\\par\\smallskip")
    L += ["\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{l" + "c" * len(cols) + "}", "\\toprule",
          "\\multicolumn{%d}{l}{\\textbf{A. Test B forecast RMSE (pp), mean $\\pm$ seed SD, by training conditions $m$ and check-ups $k$}} \\\\" % (len(cols) + 1), "\\midrule",
          " & " + " & ".join(f"$m$={c.split('|')[0]}, $k$={c.split('|')[1]}" for c in cols) + " \\\\", "\\midrule"]
    csvA = [["Arm"] + [c.replace("|", " k=") for c in cols]]
    for x in arms:
        row = [fmt_cell(cells[c][x], marks[c].get(x)) if x in cells[c] else "--" for c in cols]
        if x == "R1":
            L.append("\\midrule")
        L.append(f"{NAME[x]} & " + " & ".join(row) + " \\\\")
        csvA.append([NAME[x].replace("$", "")] + [f"{cells[c][x]['mean_pp']:.2f} +- {cells[c][x]['seed_sd_pp']:.2f}" if x in cells[c] else "" for c in cols])
    L += ["\\bottomrule", "\\end{tabular}}", "\\par\\bigskip", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{l cc cc rrr}", "\\toprule",
          "\\multicolumn{8}{l}{\\textbf{B. Test C and S2, replicate-spread ratios, cost and training size at g4}} \\\\", "\\midrule",
          f"Arm & Test C ($n$={next(iter(T['test_c'].values()))['n_conditions']}) & S2 ($n$={next(iter(T['s2'].values()))['n_conditions']}) & $E/R_{{\\mathrm{{LOO}}}}$ & $E/R_{{\\mathrm{{WARP}}}}$ & Fit (s) & Parameters & $n_{{\\mathrm{{train}}}}$ \\\\",
          "\\midrule"]
    mC = rank_marks({x: T["test_c"][x]["mean_pp"] for x in T["test_c"]})
    mS = rank_marks({x: T["s2"][x]["mean_pp"] for x in T["s2"]})
    csvB = [["Arm", "Test C", "S2", "E/R_LOO", "E/R_WARP", "Fit s", "Parameters", "n_train_used"]]
    for x in arms:
        c_ = fmt_cell(T["test_c"][x], mC.get(x)) if x in T["test_c"] else "--"
        s_ = fmt_cell(T["s2"][x], mS.get(x)) if x in T["s2"] else "--"
        if x in g4 and ref:
            e1, e2 = f"{g4[x]['mean_pp'] / ref['R_LOO']:.2f}", f"{g4[x]['mean_pp'] / ref['R_WARP']:.2f}"
        else:
            e1 = e2 = "--"
        tm = f"{g4[x]['fit_seconds']:.1f}" if x in g4 else "--"
        npar = f"{g4[x]['n_params']:d}" if x in g4 else "--"
        ntr = f"{g4[x]['n_train_used']:d}" if x in g4 else "--"
        if x == "R1":
            L.append("\\midrule")
        L.append(f"{NAME[x]} & {c_} & {s_} & {e1} & {e2} & {tm} & {npar} & {ntr} \\\\")
        csvB.append([NAME[x].replace("$", ""), c_.replace("\\textbf{", "").replace("\\underline{", "").replace("}", "").replace("$\\pm$", "+-"), s_.replace("\\textbf{", "").replace("\\underline{", "").replace("}", "").replace("$\\pm$", "+-"), e1, e2, tm, npar, ntr])
    L += ["\\bottomrule", "\\end{tabular}}",
          "\\caption{" + ("\\textcolor{red}{SYNTHETIC DEMO -- NOT RESULTS.} " if prov.synthetic else "") +
          "Held-out accuracy of all arms over the evaluation grid. Panel A: forecast RMSE in percentage points (pp), mean over the held-out cycling conditions (the unit) $\\pm$ the SD of "
          "that mean over the final-refit seeds (reproducibility, not a confidence interval); best value per column in bold, second best underlined; $m$ = cycling training "
          "conditions, $k$ = model-visible check-ups. Panel B: Test C (35\\,$^\\circ$C) and S2 (storage); $E/R$ = the g4 error divided by the replicate spread (LOO) or the "
          "window-aware replicate predictor (WARP), descriptive only; fit time, parameters and training conditions used at g4. Intervals, tiers and tests are in Fig.~4 and Table~2.}",
          "\\end{table}"]
    TAB = Path(a.out_dir) if a.out_dir else ps.TAB_OUT
    TAB.mkdir(parents=True, exist_ok=True)
    out = TAB / f"table1{prov.suffix()}.tex"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(TAB / f"table1{prov.suffix()}.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        if prov.synthetic:
            w.writerow(["SYNTHETIC DEMO - NOT RESULTS"])
        w.writerow(["Panel A: RMSE pp, mean +- seed SD"])
        w.writerows(csvA)
        w.writerow([])
        w.writerow(["Panel B"])
        w.writerows(csvB)
    print("wrote", out)


if __name__ == "__main__":
    main()
