"""Table 2 (booktabs LaTeX + CSV): ablations and controls (PREREG_v4 section 14).

Part A: the estimated contrasts of A1 against D*, A9, AG, A2, A10 and A10P at g1 and g4 (what changes, mean paired pp difference comparator minus A1 with its BCa interval,
median error ratio with its simultaneous exact interval, tier where the statistics step assigned one).
Part B: controls (NC-1, NC-2, PC-1 to PC-3) from controls.json and the Gate G record; Q-T from the secondary family; the outcome-table state and title reached.
Inputs: --analysis (contrasts_v4_B.json, controls.json). READ-ONLY: every number, tier and sentence is read from those files; only the arm-definition strings are typed.
NOT AVAILABLE (gaps): the NC-2 row and the PC-2 / PC-3 verdicts are not written by the statistics step on the Design R2 path (printed as "not evaluated"); the candidates
(A11, A12, A4, A5) against A1 individually are not in the estimated tables.
"""
import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pk_style as ps
import pk_data as pdt

CHANGES = [  # (comparator, what changes relative to A1; arm definitions of PREREG_v4 7.1)
    ("D*", "best tuned data-driven learner (inner-CV choice of A9, A11, A12)"),
    ("A9", "no residual, no law ($\\lambda=0$): data-only $F$ with the same $z_c$, inputs and window inversion"),
    ("AG", "cyclic stress map: best additive law (A4 or A5, inner-CV choice)"),
    ("A2", "exact integration of the same law, no $F$ and no residual (hard ODE)"),
    ("A10", "dataset authors' semi-empirical superposition, per-cell factor"),
    ("A10P", "dataset authors' semi-empirical superposition, as published"),
]


def tex(s):
    return str(s).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")


def mn(v, nd=2):
    return f"{v:.{nd}f}".replace("-", "$-$")


def main():
    ap = ps.common_args(__doc__)
    ap.add_argument("--analysis", required=True)
    a = ap.parse_args()
    an = Path(a.analysis)
    prov = ps.Provenance(an)
    prov.require_frozen("Table 2")
    S = pdt.load_stats(an / "contrasts_v4_B.json")
    CT = ps.load_json(ps.need(an / "controls.json"))
    L = ["% Table 2, generated by code/figures/table2.py from the statistics-step files; do not edit by hand."]
    if prov.synthetic:
        L.append("% SYNTHETIC DEMO - NOT RESULTS")
    L += ["\\begin{table}[t]", "\\centering\\footnotesize\\setlength{\\tabcolsep}{3.0pt}"]
    if prov.synthetic:
        L.append("{\\color{red}\\bfseries SYNTHETIC DEMO -- NOT RESULTS}\\par\\smallskip")
    L += ["\\begin{tabular}{l p{4.0cm} l c c c}", "\\toprule", "\\multicolumn{6}{l}{\\textbf{A. Comparators against PINN-KAN (A1) on held-out cycling conditions}} \\\\", "\\midrule",
          "Arm & What changes & Cell & $\\Delta$RMSE (pp) [95\\% BCa] & Ratio [simult. int.] & Tier \\\\", "\\midrule"]
    rows = [["Arm", "What changes", "Cell", "Delta RMSE pp [BCa]", "Ratio [simultaneous]", "Tier"]]
    for comp, what in CHANGES:
        for cell, nm in ((pdt.G1, "g1"), (pdt.G4, "g4")):
            er = pdt.est_rows(S, comp, cell)
            if not er:
                continue
            e = er[0]
            ci = e.get("mean_pp_ci")
            d = f"{mn(e['mean_pp'])} [{mn(ci[0])}, {mn(ci[1])}]" if ci else mn(e["mean_pp"])
            r = f"{np.exp(e['median_L']):.2f} [{np.exp(e['simultaneous']['lo']):.2f}, {np.exp(e['simultaneous']['hi']):.2f}]" + ("$^{\\dagger}$" if e["simultaneous"].get("is_range") else "")
            t = pdt.tier_text(pdt.tier_read(S, comp, cell))
            L.append(f"{comp if nm == 'g1' else ''} & {what if nm == 'g1' else ''} & {nm} & {d} & {r} & {t} \\\\")
            rows.append([comp, what.replace("$", "").replace("\\", ""), nm, d.replace("$", ""), r.replace("$", "").replace("\\dagger", "+"), t])
    L += ["\\bottomrule", "\\end{tabular}", "\\par\\bigskip",
          "\\begin{tabular}{>{\\raggedright\\arraybackslash}p{4.4cm} >{\\raggedright\\arraybackslash}p{5.6cm} >{\\raggedright\\arraybackslash}p{4.6cm}}", "\\toprule",
          "\\multicolumn{3}{l}{\\textbf{B. Controls, Q-T and the outcome reached}} \\\\", "\\midrule", "Item & Record & Result \\\\", "\\midrule"]
    neg, pos, gate = CT.get("negative") or {}, CT.get("positive") or {}, CT.get("gate_G", {})
    ok = lambda b: "not evaluated" if b is None else ("pass" if b else "FAIL")
    nc1, nc2 = neg.get("nc1"), neg.get("nc2")
    B = []
    B.append(("NC-1 (gate G)", (f"label invariance, max $|\\Delta\\hat y|$ = {nc1['max_abs_diff']:.1e} over {nc1['n_rows']} rows" if nc1 else "no invariance.json"), ok(nc1["passed"]) if nc1 else "not evaluated"))
    B.append(("NC-2", (f"stress vectors permuted, {nc2['k_positive']}/{nc2['n']} positive" if nc2 else "not produced on the Design R2 path"), ok(nc2["passed"]) if nc2 else "not evaluated"))
    B.append(("PC-1 (gate G)", "G0 pipeline check, nRMSE $\\le 0.15$", ok(pos.get("P1_G0_nrmse_leq_0p15"))))
    rc = gate.get("reported_checks", {})
    B.append(("PC-2", "calendar rate increases with temperature", ok(rc.get("PC-2_calendar_rate_monotone_in_T"))))
    B.append(("PC-3", "A1 beats persistence at g4", ok(rc.get("PC-3_A1_beats_persistence"))))
    B.append(("Gate G", "; ".join(gate.get("reasons", [])) or "not tripped" + (f"; not evaluated: {', '.join(gate['not_evaluated'])}" if gate.get("not_evaluated") else ""), "tripped" if gate.get("tripped") else "open"))
    qt = S["secondary"]["tests"].get("QT_g1")
    mv = S["mean_vs_median"]["contrasts"].get("QT_g1")
    if qt:
        B.append(("Q-T (A13 against A1, g1)", S.get("qualifier_sentences", {}).get("QT_g1", "") + (f" mean {mn(mv['mean_pp'])} pp" if mv else ""), "tier " + pdt.tier_text(qt["tier"])))
    oc = S.get("outcome", {})
    if oc and not oc.get("gate_G"):
        B.append(("Outcome table", f"states {oc['P']} / {oc['K']}, extent {oc['extent_clause']}, title {oc['title_id']}: {oc['title']}" + (" (provisional: rows or controls not run)" if oc.get("provisional") else ""), f"M1 {oc['M1']}, M2 {oc['M2']}, M3 {oc['M3']}"))
    for it, rec, res in B:
        L.append(f"{tex(it) if '$' not in it else it} & {rec if '$' in rec else tex(rec)} & {tex(res)} \\\\")
        rows.append([it, rec.replace("$", "").replace("\\", ""), res])
    L += ["\\bottomrule", "\\end{tabular}",
          "\\caption{" + ("\\textcolor{red}{SYNTHETIC DEMO -- NOT RESULTS.} " if prov.synthetic else "") +
          "Ablations, controls and outcome. Part A: $\\Delta$RMSE = comparator minus A1, mean over held-out conditions with its 95\\,\\% BCa interval; ratio = median over conditions of "
          "comparator/A1 error with the simultaneous exact interval of the statistics step ($^{\\dagger}$: the interval is the range of the conditions); the tier is shown only for the gated and "
          "secondary contrasts (S superior, N non-inferior, --- neither). Part B: all entries are records of the statistics step; ``not evaluated'' means that the step did not produce the record.}",
          "\\end{table}"]
    TAB = Path(a.out_dir) if a.out_dir else ps.TAB_OUT
    TAB.mkdir(parents=True, exist_ok=True)
    out = TAB / f"table2{prov.suffix()}.tex"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(TAB / f"table2{prov.suffix()}.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        if prov.synthetic:
            w.writerow(["SYNTHETIC DEMO - NOT RESULTS"])
        w.writerows(rows)
    print("wrote", out)


if __name__ == "__main__":
    main()
