"""Table 2 (booktabs LaTeX + CSV): ablations, controls and what each changes (PREREG_v2 section 14).

Part A, Test B: for each ablation arm the change relative to PINN-KAN (A1), its parameters, the mean paired RMSE difference in pp
(comparator minus A1, 95 % BCa interval), the median error ratio with its exact order-statistic interval, the number of conditions
in which A1 is better, and the tier (statistics step). Part B: negative and positive controls (analysis/controls.json).
Inputs: --run-b, --analysis (contrasts_B.json, controls.json). The 'what changes' strings are the arm definitions of PREREG_v2 7.1.
"""
import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pk_style as ps
import pk_data as pdt
from table1 import entry_for, tier_text

CHANGES = [  # (arm, hypothesis, what changes relative to A1)
    ("A9", "H1a", "no residual, no law ($\\lambda=0$): data-only $F$ with the same $z_c$, inputs and window inversion"),
    ("A3", "H1b", "cyclic stress map: log-linear Arrhenius / power-law factors"),
    ("A4", "H1b", "cyclic stress map: additive GAM (KAN without hidden layer)"),
    ("A5", "H1b", "cyclic stress map: GAM with three tensor-product terms"),
    ("A7", "H1b", "cyclic stress map: tanh MLP, parameters capped at the largest A1 map"),
    ("A2", "H2", "exact integration of the same law, no $F$ and no residual (hard ODE)"),
    ("A13", "X1", "trained on cycling cells only (no storage cells)"),
    ("A10", "H6", "dataset authors' semi-empirical superposition with per-cell factor"),
]


def main():
    ap = ps.common_args(__doc__)
    ap.add_argument("--run-b", required=True)
    ap.add_argument("--analysis", required=True)
    a = ap.parse_args()
    prov = ps.Provenance(a.run_b, a.analysis)
    prov.require_frozen("Table 2")
    an = Path(a.analysis)
    con = pdt.load_contrasts(an / "contrasts_B.json")
    ctl = ps.load_json(ps.need(an / "controls.json"))
    M = pdt.load_metrics(a.run_b)["outer_test"]
    synth = prov.synthetic
    L = ["% Table 2, generated by code/figures/table2.py from run files; do not edit by hand."]
    if synth:
        L.append("% SYNTHETIC DEMO - NOT RESULTS")
    L += ["\\begin{table}[t]", "\\centering\\footnotesize\\setlength{\\tabcolsep}{3.4pt}"]
    if synth:
        L.append("{\\color{red}\\bfseries SYNTHETIC DEMO -- NOT RESULTS}\\par\\smallskip")
    L += ["\\begin{tabular}{l l p{4.6cm} r c c c}", "\\toprule",
          "\\multicolumn{7}{l}{\\textbf{A. Ablations on Test B (held-out cycling conditions)}} \\\\", "\\midrule",
          "Arm & Hyp. & What changes relative to A1 & Param. & $\\Delta$RMSE (pp) [95\\% BCa] & Ratio [95\\% int.] & Tier \\\\", "\\midrule"]
    rows = []
    for arm, hyp, what in CHANGES:
        ent, tier, status = entry_for(con, arm)
        if ent is None:
            continue
        lo, hi = ent["mean_pp_ci95"]
        mlo, mhi = ent["median_ci95"]
        d = f"{ent['mean_pp']:.2f} [{lo:.2f}, {hi:.2f}]".replace("-", "$-$")
        r = f"{np.exp(ent['median_L']):.2f} [{np.exp(mlo):.2f}, {np.exp(mhi):.2f}]"
        t = tier_text(tier, status)
        np_ = M[arm]["n_params"]
        L.append(f"{arm} & {hyp} & {what} & {np_} & {d} & {r} & {t} \\\\")
        rows.append([arm, hyp, what.replace("$", "").replace("\\", ""), np_, f"{ent['mean_pp']:.2f} [{lo:.2f}, {hi:.2f}]", r, t])
    L += ["\\bottomrule", "\\end{tabular}", "\\par\\bigskip",
          "\\begin{tabular}{>{\\raggedright\\arraybackslash}p{4.8cm} >{\\raggedright\\arraybackslash}p{3.3cm} >{\\raggedright\\arraybackslash}p{3.3cm} >{\\raggedright\\arraybackslash}p{3.3cm}}", "\\toprule",
          "\\multicolumn{4}{l}{\\textbf{B. Controls}} \\\\", "\\midrule",
          "Control & Statistic & Observed & Required / outcome \\\\", "\\midrule"]
    neg, pos = ctl["negative"], ctl["positive"]
    ok = lambda b: "pass" if b else "FAIL"
    mn = lambda v, nd=3: f"{v:.{nd}f}".replace("-", "$-$")
    nc1, nc2 = neg.get("nc1"), neg.get("nc2")      # D014: NC-1 label invariance (gate G), NC-2 permuted stress (interpretive, not gating)
    if nc1:
        L.append("NC-1 (gate G): post-window labels of held-out cells replaced by garbage & max $|\\Delta\\hat y|$ over "
                 f"{nc1['n_rows']} predictions & {nc1['max_abs_diff']:.1e} & identical (0): {ok(nc1['passed'])} \\\\")
    if nc2:
        L.append("NC-2: stress vectors permuted among conditions (A1 re-run; not gating) & median $L=\\ln(S_{\\mathrm{perm}}/S_{\\mathrm{real}})$, "
                 f"{nc2['k_positive']}/{nc2['n']} positive & {mn(nc2['median_L'])} [{mn(nc2['median_ci95'][0])}, {mn(nc2['median_ci95'][1])}] & exact sign test $p={nc2['p_one_sided_exact']:.3f}$ "
                 f"$\\le 0.025$: {ok(nc2['passed'])} \\\\")
    L.append(f"Positive P1: well-specified synthetic G0 & nRMSE of recovered surface & -- & $\\le 0.15$: {ok(pos['P1_G0_nrmse_leq_0p15'])} \\\\")
    L.append(f"Positive P2: storage cells & calendar rate against $T$ & monotone at every SOC in the hull & {ok(pos['P2_monotone_in_T'])} \\\\")
    L.append(f"Positive P3: PINN-KAN against persistence & median $L$ & {mn(pos['P3_A1_beats_R1_median_L'], 2)} & $>0$: {ok(pos['P3_A1_beats_R1_median_L'] > 0)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          "\\caption{" + ("\\textcolor{red}{SYNTHETIC DEMO -- NOT RESULTS.} " if synth else "") +
          "Ablations and controls. Part A: each row changes one component of PINN-KAN (A1). $\\Delta$RMSE = comparator minus A1, mean over held-out "
          "conditions with its 95\\,\\% BCa interval; ratio = median over conditions of comparator/A1 error with its exact 95\\,\\% order-statistic "
          "interval (above 1: A1 better); tier from the preregistered sign test (S superior, N non-inferior, -- neither; n.t.\\ gated; "
          "desc.\\ descriptive). Pool arms A3--A7 are descriptive, Holm over the four. Part B: controls of PREREG\\_v2 section 10; $L=\\ln$(error of comparator / "
          "error of A1) per condition.}", "\\end{table}"]
    TAB = Path(a.out_dir) if a.out_dir else ps.TAB_OUT
    TAB.mkdir(parents=True, exist_ok=True)
    out = TAB / f"table2{prov.suffix()}.tex"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(TAB / f"table2{prov.suffix()}.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        if synth:
            w.writerow(["SYNTHETIC DEMO - NOT RESULTS"])
        w.writerow(["Arm", "Hypothesis", "What changes", "Parameters", "Delta RMSE pp [95% BCa]", "Ratio [95% int.]", "Tier"])
        w.writerows(rows)
        w.writerow([])
        w.writerow(["Controls", json_dump(ctl)])
    print("wrote", out)


def json_dump(o):
    import json
    return json.dumps(o)


if __name__ == "__main__":
    main()
