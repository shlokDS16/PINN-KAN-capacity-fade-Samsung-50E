"""FB-2: A10 parameter recovery on data generated from the dataset authors' published equations (JES 142, 119552 Eq. 18, SI S.3) with their published parameter values
(Tables D.2 case 3, D.3 case 2). No Samsung capacity value is read: the stress design comes from the synthetic generator. Writes runs/fb2_a10/metrics.json.
    .venv/Scripts/python.exe -P code/pilots/fb2_a10_recovery.py"""
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "code"))
sys.path.insert(0, os.path.join(ROOT, "code", "tests"))
os.environ["CUDA_VISIBLE_DEVICES"] = "-1"

import numpy as np

import test_pk_a10_paper_form as T
from pinnkan import semi

out = {"what": "A10 recovery of the published parameters from data generated by the published equations (noise-free and sigma = 0.00274)", "eolc": T.EOLC, "cal_ref": T.CAL_REF, "cyc_ref": T.CYC_REF,
       "paper_theta_cal": T.TH_CAL, "paper_theta_cyc": T.TH_CYC, "convention": "SI Eq. S.3", "runs": {}}
true = T.paper_to_code()
for name, seed, sigma in (("noise_free", 4, 0.0), ("sigma_0.00274", 5, 0.00274)):
    cells, _ = T._cells_from_paper(seed, sigma)
    form, hat, cost = T._fit(cells)
    eff = lambda h: dict(th_cal0=h[1] * 1e4 / h[3], a_soc_cal=h[2] / h[3], th_cal2=1 / h[3], th_cyc0=h[5] * 1e4 / h[10], a_smax=h[6] / h[10], a_cch=h[7] / h[10], a_cdch=h[8] / h[10],
                         a_dod=h[9] / h[10], th_cyc5=1 / h[10])
    err = [form.loss(hat, c.raw, c.t[1:], c.efc[1:]) - form.loss(true, c.raw, c.t[1:], c.efc[1:]) for c in cells if c.n > 1]
    out["runs"][name] = dict(seed=seed, sigma=sigma, n_cells=len(cells), n_points=int(sum(c.n - 1 for c in cells)), cost=cost, fitted_code_theta=hat.tolist(), true_code_theta=true.tolist(),
                             effective_fitted=eff(hat), effective_true=eff(true), rmse_loss_vs_true_loss=float(np.sqrt(np.mean(np.concatenate(err) ** 2))),
                             max_rel_err_code_theta=float((np.abs(hat - true) / np.maximum(np.abs(true), 0.3)).max()))
out["git_commit"] = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
os.makedirs(os.path.join(ROOT, "runs", "fb2_a10"), exist_ok=True)
json.dump(out, open(os.path.join(ROOT, "runs", "fb2_a10", "metrics.json"), "w"), indent=1, default=float)
for k, v in out["runs"].items():
    print(k, "cost", v["cost"], "max rel err", v["max_rel_err_code_theta"], "rmse", v["rmse_loss_vs_true_loss"])
