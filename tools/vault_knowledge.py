"""Build the project's knowledge graph in the Obsidian vault (no LLM, stdlib only).

graph-memory sync calls this as:  python -I tools/vault_knowledge.py --vault-dir <vault>/Projects/<name>
Run by hand the same way. It rewrites <vault-dir>/knowledge/ from scratch on every run (generated: do not edit there).

Sources (repo is the single source of truth):
  research/PROJECT_CONTEXT.md   -> knowledge/context/*.md   (one note per section)
  research/DECISIONS.md         -> knowledge/decisions/D0xx.md + decisions/INDEX.md (links between decisions)
  notes/exemplars/*.md, notes/exemplars/deep/*.md -> knowledge/exemplars/*.md (copies)
  research/audits/*.md          -> knowledge/audits/*.md (copies)
  the glossary below            -> knowledge/entities/*.md (with the decisions that mention each entity)
"""
import argparse, os, re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
P = "Projects/PINN KAN battery paper/knowledge"      # vault-relative prefix for wikilinks

# name: (regex that finds a mention, one-line description)
ENTITIES = {
    "Journal of Energy Storage": (r"\bJES\b|Journal of Energy Storage", "Target journal (Elsevier, ISSN 2352-152X); D001."),
    "Design R2": (r"Design R2", "Current study design: m x k data-efficiency grid, ablation ladder, KAN vs GAM law, closed outcome table (D016)."),
    "Closed outcome table": (r"closed outcome table|outcome table|section 11\b", "Titles T1-T9 chosen by the results, never by hand; PREREG_v4 section 11 (D017, D019, D030)."),
    "PREREG_v4": (r"PREREG_v4|PREREG v4|prereg(istration)? v4", "The preregistration to be frozen (runs/prereg/PREREG_v4.md)."),
    "FROZEN": (r"\bFROZEN\b|freeze", "The freeze flag file runs/prereg/FROZEN and the freeze procedure (D031, D036, D039)."),
    "Samsung INR21700-50E": (r"Samsung|50E", "Primary dataset (Stroebl et al., JES 142, 119552): 279 cells, 40 cycling + 19 storage conditions."),
    "ISU-ILCC": (r"\bISU\b", "Secondary dataset (cyclic ageing)."),
    "SNL": (r"\bSNL\b", "Sandia dataset used as a check."),
    "NASA-CALCE addendum": (r"NASA|CALCE", "Descriptive addendum on public datasets (D022)."),
    "KAN": (r"\bKAN\b|Kolmogorov", "Kolmogorov-Arnold network stress functions and closed-form law extraction."),
    "PINN": (r"\bPINN\b|physics-informed", "Physics-informed neural network with storage and cycling degradation terms."),
    "Sign test": (r"sign test", "Confirmatory test: design-effect sign test on condition log error ratios (D012, D018)."),
    "Negative and positive controls": (r"NC-1|NC-2|PC-1|PC-2|PC-3|negative control", "NC-1 and PC-1 form gate G; NC-2 interpretive; PC-2, PC-3 reported checks."),
    "Item (f)": (r"item \(f\)", "Post-freeze training-side dependence runs at g1 before any test fold (D026)."),
    "C-rate ablation": (r"C-rate ablation|row \(u\)|neutralise_stress", "Descriptive row 9.9 (u): C-rate inputs set to the training median at g4 (D041)."),
    "Stroebl 2026": (r"Stroebl", "Dataset authors' paper and mandatory comparator A10 (JES 142, 119552)."),
    "Lucu 2020": (r"Lucu", "Learning curves for ageing tests (JES 30, 101409/101410); shapes T5/T6 (D029, D030)."),
    "PIKAN and PGKAN": (r"PIKAN|PGKAN", "Nearest PINN+KAN SOH prior work in JES 2026; claim the combination only."),
    "KA-CRNN": (r"KA-CRNN", "KAN-Arrhenius neural ODE precedent (JES 158, 121853)."),
    "Red team": (r"red team|red-team", "Adversarial reviewer; signs prereg rows (research/audits/)."),
    "Statistician": (r"statistician", "Owns the analysis plan and signs statistics rows."),
    "Gate auditor": (r"gate auditor|gate-auditor", "Checks exit criteria on disk; ticks the freeze."),
}


def link(kind, name, label=None):
    return f"[[{P}/{kind}/{name}|{label or name}]]"


def safe(name):
    return re.sub(r'[\\/:*?"<>|]+', "-", name).strip()


def mentions(text):
    return [e for e, (rx, _) in ENTITIES.items() if re.search(rx, text, re.I)]


def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def parse_decisions():
    text = (ROOT / "research" / "DECISIONS.md").read_text(encoding="utf-8")
    parts = re.split(r"(?m)^### (D\d{3}[a-z]?) ", text)
    out = {}
    for i in range(1, len(parts) - 1, 2):
        did, rest = parts[i], parts[i + 1]
        title, _, body = rest.partition("\n")
        body = re.split(r"(?m)^## ", body)[0]              # stop at the next level-2 section, if any
        out[did] = (title.strip(), body.strip())
    return out


def build(vd):
    kd = vd / "knowledge"
    if kd.exists():
        shutil.rmtree(kd)
    gen = "_Generated by tools/vault_knowledge.py from the repo; edit the repo, not this note._"
    hub = [f"# PINN KAN battery paper: knowledge hub", "", gen, "",
           "Target: **Journal of Energy Storage** (Elsevier). Read the context notes first.", "", "## Context"]

    # context sections
    ctx = (ROOT / "research" / "PROJECT_CONTEXT.md").read_text(encoding="utf-8")
    secs = re.split(r"(?m)^## ", ctx)
    names = []
    for s in secs[1:]:
        head, _, body = s.partition("\n")
        name = safe(re.sub(r"^\d+\.\s*", "", head.strip()))
        names.append(name)
        ents = mentions(body)
        write(kd / "context" / f"{name}.md", [f"# {head.strip()}", "", gen, "", f"Up: [[{P}/HUB|HUB]]", "", body.strip(), "",
              "## Entities", *[f"- {link('entities', safe(e), e)}" for e in ents]])
        hub.append(f"- {link('context', name)}")

    # decisions
    dec = parse_decisions()
    idx = ["# Decisions", "", gen, "", f"Up: [[{P}/HUB|HUB]]", "", "| ID | Title |", "|---|---|"]
    ent_dec = {e: [] for e in ENTITIES}
    for did, (title, body) in dec.items():
        refs = sorted(set(re.findall(r"\bD\d{3}[a-z]?\b", body)) - {did})
        ents = mentions(title + "\n" + body)
        for e in ents:
            ent_dec[e].append(did)
        write(kd / "decisions" / f"{did}.md", [f"# {did} {title}", "", gen, "", f"Up: {link('decisions', 'INDEX', 'Decisions')}", "",
              body, "", "## Links", *[f"- {link('decisions', r)}" for r in refs if r in dec],
              *[f"- {link('entities', safe(e), e)}" for e in ents]])
        idx.append(f"| {link('decisions', did)} | {title.replace('|', '/')} |")
    write(kd / "decisions" / "INDEX.md", idx)
    hub += ["", "## Decisions", f"- {link('decisions', 'INDEX', 'All decisions')} ({len(dec)})"]

    # entities
    hub += ["", "## Entities"]
    for e, (_, desc) in ENTITIES.items():
        write(kd / "entities" / f"{safe(e)}.md", [f"# {e}", "", gen, "", desc, "", f"Up: [[{P}/HUB|HUB]]", "",
              "## Decisions that mention it", *[f"- {link('decisions', d)}" for d in ent_dec[e]]])
        hub.append(f"- {link('entities', safe(e), e)}")

    # copies of exemplar notes and audits
    for kind, globs in (("exemplars", ["notes/exemplars/*.md", "notes/exemplars/deep/*.md"]), ("audits", ["research/audits/*.md"])):
        hub += ["", f"## {kind.capitalize()}"]
        for g in globs:
            for f in sorted(ROOT.glob(g)):
                body = f.read_text(encoding="utf-8", errors="replace")
                ents = mentions(body)
                write(kd / kind / f.name, [f"_Copy of `{f.relative_to(ROOT).as_posix()}`. {gen[1:-1]}_", "", f"Up: [[{P}/HUB|HUB]]",
                      *[f"- {link('entities', safe(e), e)}" for e in ents], "", body])
                hub.append(f"- {link(kind, f.stem)}")
    write(kd / "HUB.md", hub)
    n = sum(1 for _ in kd.rglob("*.md"))
    print(f"knowledge hub: {n} notes ({len(names)} context, {len(dec)} decisions, {len(ENTITIES)} entities) in {kd}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--vault-dir", required=True)
    build(Path(ap.parse_args().vault_dir))
